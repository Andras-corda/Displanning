/* Normalise un code de salle pour la recherche : majuscules, espaces retirés. */
function normalizeCode(code) {
  return code.toUpperCase().replace(/\s+/g, '');
}

function buildLookup(table) {
  const map = new Map();
  for (const [code, url] of Object.entries(table)) map.set(normalizeCode(code), url);
  return map;
}

